"""One ROI vocabulary, and two independent maps into it.

**This module is what makes the two atlases peers rather than one being a subordinate of
the other.**  NMM and DK each parcellate the brain in their own words; this file names the
regions the *analysis* speaks in, and gives each atlas its own, separate mapping onto them.
Neither map consults the other, and neither atlas's scope is defined in terms of the other's
labels.  The names here are the ones that reach the figure legends and the ``nmm_roi`` /
``dk_roi`` columns of ``channels.pkl``.

What this replaces.  Agreement used to be scored by reducing NMM through
``label._CANONICAL`` and DK through ``surface.DK_CANONICAL`` into a third, coarser set of
comparison keys, with ``DK_MAY_SHARE`` policing the cases where two DK parcels collapsed
onto one key.  That machinery existed *because* there was no shared vocabulary.  With one,
agreement is ROI equality, and the invariant ``DK_MAY_SHARE`` was enforced by test is
structural instead: two parcels cannot silently become the same structure, because the ROI
each maps to is written down.

Three rules this file exists to keep:

1. **A label with no entry here has no ROI, and is therefore out of the analysis.**  The
   scope stays a whitelist for the reason ``AGENTS.md`` gives -- a new participant can carry
   parcels nobody has hit before, and under a blacklist those enter the analysis silently.
   Contacts still get a readable name (see :func:`roi_of`); what they do not get is
   membership.
2. **An unsplit parent parcel is not an ROI.**  ``Left MTG middle temporal gyrus`` maps to
   nothing: the vocabulary is ``aMTG``/``pMTG``, and a contact whose parcel was never split
   has no anterior/posterior call to report.  This matters for the one bilateral
   participant -- ``Right MTG middle temporal gyrus`` skips subdivision, because
   ``subdivide.SUBDIVISIONS`` is keyed on ``Left ...``, and it used to come back with an
   *empty* exclusion reason because :func:`config.strip_hemisphere` made it match the
   whitelist. Only the clinical exclusion kept those 27 contacts out of the analysis. Now
   the vocabulary keeps them out.
3. **Comparability is structural.**  A pair is comparable only when both ROIs are
   expressible by both atlases, so DK's ``pSTS`` and NMM's ``frontal operculum`` are
   reported as *not comparable* rather than as disagreements.  "The other atlas has no such
   parcel" and "the two atlases disagree" are different facts and are never pooled.

--------------------------------------------------------------------------------
VENDORED -- do not edit this file's vocabulary by hand.

Source   : Speech/electrode_labeling, `electrode_labeling/roi.py`
Commit   : 974dc0d7218b58c9bff4f888afed1f5cc9737d49  ("Make NMM and DK peers via a
           shared ROI vocabulary", 2026-08-08) plus **uncommitted working-tree changes**
           -- the 2026-08-23 `tp` -> `tpm` re-scope has not been committed in the sibling.
           Re-run the drift check after that commit lands.
Vendored : 2026-08-23, verbatim above the `EXCLUDED CONTACTS` banner below.

What changed on 2026-08-23: the analysis moved from `tp` (13 regions) to `tpm` (18).  The
five medial and deep regions -- entorhinal, parahippocampal, precuneus, insula, cingulate --
are now `in_analysis`, so `EXCLUDED_BY_REASON` no longer has a `medial` key at all.
`utils/roi_scopes.py` guarded on that key being non-empty and had to be reworked in the same
change.  `PALETTE_SCOPE` (23) is new: it is what the palette pins, deliberately wider than
the analysis so a `tpfm` figure has colours for its frontal regions.

Why a copy and not an import: `electrode_labeling` is a separate git repository on this
machine, not an installed package, and it needs nibabel/scipy/h5py plus the `N:` imaging
share that `main` has no reason to depend on.  This module is the part that needs none of
that -- pure stdlib, `typing.NamedTuple` only.

Why a copy and not a re-implementation: this exact table is what *generated* the `nmm_roi`
and `dk_roi` columns in `data/{PAT}/{PAT}_*channels.pkl`.  A second, hand-written table can
silently disagree with the one that produced the data, which would make both atlases
meaningless without anything failing.  `_index()` below raises if two labels claim one ROI,
so the copy is self-checking.

Drift is caught by `python scripts/check_roi_vocabulary.py --sibling <path>`; run it after
pulling either repository.  To change the vocabulary, edit the sibling, re-run its
`writeback` stage so the columns match, then re-vendor -- never the other way round.
--------------------------------------------------------------------------------
"""
from __future__ import annotations

from typing import NamedTuple


class ROI(NamedTuple):
    """One region in the analysis vocabulary, and how each atlas spells it."""

    name: str
    #: Palette family, or ``None`` for a region that is never given its own colour.
    family: str | None
    #: Rank within the family, anterior/ventral first.  Fixed, never derived from counts.
    order: int
    #: Why the analysis sets this region aside; ``""`` means it is in the analysis.
    reason: str
    #: The NMM labels that map here, post-merge and post-subdivision.
    nmm: tuple[str, ...]
    #: The DK labels that map here, post-merge and post-subdivision.
    dk: tuple[str, ...]

    @property
    def in_analysis(self) -> bool:
        return self.reason == ""

    @property
    def atlases(self) -> frozenset:
        return frozenset({a for a, labels in (("nmm", self.nmm), ("dk", self.dk)) if labels})


