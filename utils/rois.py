BY_NAME: dict[str, ROI] = {roi.name: roi for roi in _TABLE}

#: The regions that can be given a colour, in table order.  A region with no family falls to
#: the `other` grey and `palette.propose` warns rather than inventing one, so growing the
#: palette stays a decision someone makes on purpose.
ROIS_WITH_FAMILY: tuple[ROI, ...] = tuple(r for r in _TABLE if r.family)

#: reason -> the ROIs dropped for it.  Derived, so it cannot drift from the table; it exists
#: because reports name the *groups* ("subcortical (Hippocampus, Amygdala, ...)") rather than
#: listing every region flat.
EXCLUDED_BY_REASON: dict[str, tuple[str, ...]] = {
    reason: tuple(r.name for r in _TABLE if r.reason == reason)
    for reason in dict.fromkeys(r.reason for r in _TABLE if r.reason)
}

#: In-analysis ROI names, in table order.  **The whitelist.**  18 regions: the lateral and
#: ventral temporal lobe, lateral parietal cortex, and the medial and deep cortex that
#: joined on 2026-08-23 when the scope moved from `tp` (13) to `tpm`.
IN_ANALYSIS: tuple[str, ...] = tuple(r.name for r in _TABLE if r.in_analysis)

#: Every region **any** supported scope can select: the analysis plus the frontal regions
#: `tpfm` adds.  23 names.
#:
#: This is what the palette pins, and it is deliberately wider than :data:`IN_ANALYSIS`.
#: Pinning only the analysis meant a figure drawn at `tpfm` rendered its frontal regions as
#: the reserved `other` grey -- the scope said "include these" and the palette had no colour
#: to offer.  Pinning the wider set costs nothing measurable: the worst CIEDE2000 pair in the
#: palette is 7.84 (`pSTG`/`pSTS`) at 13, 18 and 23 regions alike.
#:
#: What stops a figure naming a region it never drew is no longer this set -- it is
#: `palette.legend_entries(regions=...)`, which the figure calls with what it actually
#: plotted.  That check moved from pin time to draw time on purpose: pin time could only ever
#: guess which scope a future figure would use.
PALETTE_SCOPE: tuple[str, ...] = IN_ANALYSIS + EXCLUDED_BY_REASON.get(FRONTAL, ())


#: Marks a region on the non-default side.  Left is the default and unprefixed.
RIGHT_PREFIX = "Right "


def strip_hemisphere(label: str) -> str:
    for prefix in ("Left ", RIGHT_PREFIX):
        if label.startswith(prefix):
            return label[len(prefix):]
    return label


def _index(attr: str) -> dict[str, str]:
    """atlas label -> ROI, keyed **hemisphere-agnostically**.

    Both `Left PP planum polare` and the bare `PP planum polare` are stored, the same way
    :func:`subdivide.merge_map` already does it.  Without the bare key a right-hemisphere
    parcel misses the map, falls through to the raw string, and produces a *second spelling*
    of a region that already has one -- `PP planum polare` beside `planum polare` -- which
    would count as two regions in any table built from these columns.
    """
    out: dict[str, str] = {}
    for roi in _TABLE:
        for label in getattr(roi, attr):
            for key in {label, strip_hemisphere(label)}:
                if out.get(key, roi.name) != roi.name:
                    raise ValueError(f"{attr} label {key!r} maps to both "
                                     f"{out[key]!r} and {roi.name!r}")
                out[key] = roi.name
    return out


#: atlas label -> ROI name.  Built from :data:`_TABLE`, so the two cannot drift apart, and
#: raising on a duplicate is what stops one label quietly serving two regions.
NMM_TO_ROI: dict[str, str] = _index("nmm")
DK_TO_ROI: dict[str, str] = _index("dk")

_MAPS = {"nmm": NMM_TO_ROI, "dk": DK_TO_ROI}

#: ROI pairs that are neither equal nor a disagreement, declared once and symmetric.
#:
#: Kept deliberately short.  Most of what the old `DK_MAY_SHARE` had to declare is now
#: handled structurally by :func:`comparable` -- a region only one atlas can express is not
#: compared at all -- so what remains is genuine containment between two regions both
#: atlases *do* have.
RELATED: dict[frozenset, str] = {
    frozenset({"entorhinal", "parahippocampal"}):
        "entorhinal cortex sits on the parahippocampal gyrus -- genuine containment, and it "
        "holds whichever atlas said which",
}


def roi_of(label: str, atlas: str) -> str:
    """The ROI this atlas label belongs to, or a readable fallback name.

    **Left is the default and carries no prefix; a right-hemisphere region is written
    ``Right <roi>``.**  The cohort is left-only -- every participant but one, and that one's
    right shank was clinically excluded -- so a bare name means left and the prefix appears
    only where there is something to flag.

    That asymmetry is deliberate rather than cosmetic.  Merging the two sides would put
    right-hemisphere contacts into a left-hemisphere region's counts, silently; keeping the
    prefix means `Right planum polare` is **not** in :data:`BY_NAME`, so :func:`in_analysis`
    is false for it and :func:`exclusion_reason` reports :data:`UNSCOPED`.  Right-hemisphere
    contacts therefore cannot enter the analysis by accident, which is the decision
    ``AGENTS.md`` records: they are set aside rather than half-supported. Supporting them
    means adding the regions here on purpose, not relaxing this function.

    **Every labelled contact still gets a name**, including the ones the analysis sets
    aside -- that is the contract the ``nmm_roi`` / ``dk_roi`` columns rely on.  What an
    unmapped label does not get is membership.
    """
    text = str(label)
    mapping = _MAPS[atlas]
    if text in mapping:
        return mapping[text]
    bare = strip_hemisphere(text)
    # The index carries the bare key too, so this hits for any mapped region whatever side
    # it came from.  It misses only for labels deliberately absent from the table -- the
    # unsplit parents, e.g. `Right MTG middle temporal gyrus` -- which fall through to the
    # string itself and are reported as out of scope.
    name = mapping.get(bare, bare)
    return f"{RIGHT_PREFIX}{name}" if text.startswith(RIGHT_PREFIX) else name


def in_analysis(roi: str) -> bool:
    """Whether this ROI is in the analysis.  Unknown names are **out**, never in."""
    entry = BY_NAME.get(str(roi))
    return bool(entry and entry.in_analysis)


#: Written where an atlas found nothing to label the contact with.  Recognised here, not
#: only in :mod:`label`, because "the atlas found white matter" is **not** "this region is
#: out of scope" -- they are different states and the whitelist must not report the first as
#: the second.  `label.UNASSIGNED` and `config.UNASSIGNED` are the same string.
UNASSIGNED = "unassigned"


def exclusion_reason(roi: str) -> str:
    """Why this ROI is set aside, or ``""`` if it is in the analysis.

    A name absent from the table is excluded and reported as :data:`UNSCOPED`, so it is
    noticed rather than assumed.  :data:`UNASSIGNED` and the empty string are neither: the
    atlas had nothing to say, which `usage_for` classifies as `no_grey_label`.
    """
    name = str(roi)
    if name in (UNASSIGNED, ""):
        return ""
    entry = BY_NAME.get(name)
    if entry is None:
        return UNSCOPED
    return entry.reason


def expressible_by(roi: str) -> frozenset:
    entry = BY_NAME.get(str(roi))
    return entry.atlases if entry else frozenset()


def comparable(nmm_roi: str, dk_roi: str) -> bool:
    """Whether the two atlases can be asked to agree about this pair at all.

    Both ROIs must be in the vocabulary and expressible by both atlases.  DK's ``pSTS`` and
    NMM's ``frontal operculum`` therefore never enter the agreement rate: the other atlas
    has no parcel that could confirm or contradict them, and scoring that as a disagreement
    would count a difference between the atlases as an error in the labels.
    """
    both = frozenset({"nmm", "dk"})
    return expressible_by(nmm_roi) == both and expressible_by(dk_roi) == both


def agrees(nmm_roi: str, dk_roi: str) -> bool:
    """Whether the two atlases name the same region.

    Equality in the shared vocabulary, plus the declared containments in :data:`RELATED`.
    Symmetric by construction -- there is no direction in which one atlas's answer is the
    reference the other is scored against.  Pairs that are not :func:`comparable` are not
    disagreements and return ``True``; :func:`comparable` is what separates the two, and
    every report must carry both numbers.
    """
    if not comparable(nmm_roi, dk_roi):
        return True
    return str(nmm_roi) == str(dk_roi) or frozenset({str(nmm_roi), str(dk_roi)}) in RELATED

